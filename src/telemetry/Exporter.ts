import type { TelemetryRecorder, TelemetrySample } from "./TelemetryRecorder";

export const CSV_COLUMNS: ReadonlyArray<keyof TelemetrySample> = [
  "session_id",
  "timestamp_ms",
  "track_id",
  "lap_number",
  "sector_number",
  "position_x",
  "position_z",
  "heading_deg",
  "speed_kmh",
  "throttle",
  "brake",
  "steering",
  "off_track",
  "lap_elapsed_ms",
  "collision_count",
];

function cell(v: unknown): string {
  if (typeof v === "number") return Number.isInteger(v) ? String(v) : v.toFixed(3);
  if (typeof v === "boolean") return v ? "1" : "0";
  const s = String(v ?? "");
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCSV(rec: TelemetryRecorder): string {
  const rows = rec.samples.map((s) => CSV_COLUMNS.map((c) => cell(s[c])).join(","));
  return [CSV_COLUMNS.join(","), ...rows].join("\n") + "\n";
}

export function toJSON(rec: TelemetryRecorder): string {
  return JSON.stringify(
    {
      data_origin: "simulated_game_telemetry",
      note: "Generated by TrackRush Pro on a fictional circuit. Not real-world motorsport data.",
      session: rec.info,
      sample_rate_hz: 10,
      laps: rec.laps,
      samples: rec.samples,
    },
    null,
    2,
  );
}

export function download(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
